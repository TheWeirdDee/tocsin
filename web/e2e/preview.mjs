import { chromium } from '@playwright/test'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1280, height: 860 }, deviceScaleFactor: 2 })
await p.goto('http://127.0.0.1:8000/demo/test3?cond=clean&b=3&t=6083', { waitUntil: 'networkidle' })
await p.waitForTimeout(1500)
await p.evaluate(() => window.scrollTo(0, 0))
await p.waitForTimeout(300)
await p.screenshot({ path: 'public/preview.png' })
const m = await b.newPage({ viewport: { width: 390, height: 760 }, deviceScaleFactor: 2 })
await m.goto('http://127.0.0.1:8000/demo/test3?cond=clean&b=3&t=6083', { waitUntil: 'networkidle' })
await m.waitForTimeout(1500)
await m.evaluate(() => document.querySelector('.evidence')?.scrollIntoView())
await m.waitForTimeout(300)
await m.screenshot({ path: 'public/preview-mobile.png' })
await b.close()
